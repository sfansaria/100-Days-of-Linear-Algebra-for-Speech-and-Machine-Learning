'''
lets proofread the transcript generated by an AI speech model. 
The True Reference Script - what the speaker actually said
The Model Hypothesis - what the text-recognition model typed out

lets evaluate the standard text fields like a multiple-choice test by
grading each slot as right or wrong fails because speech models add, skip or twist text positions.

voice actor clearly says: True Script: "learning speech models is fun." (5 words)
The model undergoes a slight background noise glitch and transcribes: 
Model Guess: "leaning speech extra models fun." (5 words)

Align them rigidly index-by-index like a static list, the words mismatch immediately:

Index:      0        1        2        3         4
True:    [learning] [speech] [models] [is]      [fun]
Guess:   [leaning]  [speech] [extra]  [models]  [fun]
Match?      NO        YES      NO       NO       YES  SCORE: 1/5 

A rigid look makes it seem like the model failed 80% of the sentence.
However, looking closely reveals the model actually did a decent job.
1. It simply made a tiny typo on the first word (learning -> leaning)
2. It accidentally hallucinated a random word (extra).
3. It completely skipped a word (is).
4. The words "models" and "fun" are actually correct, they just got 
   pushed out of their original index tracks.

Sequence Metric Evaluation acts like a smart human editor who slices up the
text track, slides the matching words back into alignment, and logs exactly three
specific types of editing mistakes to calculate the final score:
-> Substitution (S): The model misheard a word (learning -> leaning) [count=1]
-> Insertion (I): The model added an extra word out of nowhere (extra)[count=1]
-> Deletion (D): The model skipped a spoken word entirely (is). [count=1]

The Global Benchmark: Word Error Rate (WER)

To give this model an official grade, researchers use the Word Error Rate (WER)
formula. It totals up all the editing operations required to fix the text and 
divides them by the total count of words in the true original scripts (N=5):

WER = (Substitutions + Insertions + Deletions) / (Total True Words)

WER = (1+1+1)/5 = 3/5 = 60%

This means you need to make 3 editing adjustments for every 5 words spoken to fix the model's output.

To compute the calculation dynamically without human manual effort, the algorithm sets up a 2D dynamic 
programming coordinate system (Levenshtein Distance Grid). It treats the calculation like a pathfinding puzzle, 
finding the cheapest edit path from the top-left to the bottom-right corner of the word matrices.

'''

import torch

def compute_wer_pipeline(reference_text, hypothesis_text):
    ref_words = reference_text.split()
    hyp_words = hypothesis_text.split()

    R = len(ref_words)
    H = len(hyp_words)

    dp_grid = torch.zeros((R+1, H+1))

    for i in range(R+1):
        dp_grid[i, 0] = i

    for j in range(H+1): 
        dp_grid[0, j] = j

    
    for i in range(1, R+1):
        for j in range(1, H+1):
            if ref_words[i-1] == hyp_words[j-1]:
                dp_grid[i, j] = dp_grid[i-1, j-1]
            else:
                deletion_cost = dp_grid[i-1, j] + 1
                insertion_cost = dp_grid[i, j-1] + 1
                substitution_cost = dp_grid[i-1, j-1] + 1

                dp_grid[i, j] = min(deletion_cost, insertion_cost, substitution_cost)
    
    substitutions, insertions, deletions = 0, 0, 0
    i, j = R, H

    while i > 0 or j > 0:
        if i > 0 and j > 0 and ref_words[i-1] == hyp_words[j-1]:
            i -= 1
            j -= 1
        elif i > 0 and dp_grid[i, j] == dp_grid[i-1, j] + 1:
            deletions += 1
            i -= 1
        elif j > 0 and dp_grid[i, j] == dp_grid[i, j-1] + 1:
            insertions += 1
            j -= 1
        else:
            substitutions += 1
            i -= 1
            j -= 1
    

    wer_score = (substitutions + insertions + deletions) / R

    return wer_score, substitutions, insertions, deletions

true_sentence = "learning speech models is fun"
ai_prediction = "leaning speech extra models fun"


wer, subs, ins, dels = compute_wer_pipeline(true_sentence, ai_prediction)

print("Speech Lattice Text Path Metric Evaluation")
print(f"True Target Script: '{true_sentence}'")
print(f"AI Decoded String: '{ai_prediction}'")
print(f"Substitutions (S): {subs} ('learning' -> 'leaning')")
print(f"Insertions (I): {ins} (added 'extra')")
print(f"Deletions (D): {dels} (skipped 'is')")
print(f"Calculated Metric: {wer * 100:.1f}% Word Error Rate (WER)")